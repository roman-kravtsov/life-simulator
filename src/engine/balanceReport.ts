// The balance report (ADMIN-003) as Markdown: for each country, how the simulated lives compare with the
// source data on life expectancy, schooling, work, marriage, family, income and the causes of death.
// Written to docs/balance-report.md by `npm run balance-report` and published by CI. A pure function.
import { LE_TOLERANCE_YEARS, type Comparison, type LifeExpectancyReport } from "./calibration";
import type { Country } from "./world/types";

export interface CountryBalance {
  country: Pick<Country, "iso3" | "name" | "region" | "incomeGroup">;
  lifeExpectancy: LifeExpectancyReport;
  /** The school, work, family and income comparisons, then the causes of death. */
  comparisons: Comparison[];
}

export interface BalanceReportInput {
  countries: CountryBalance[];
  lives: number;
  contentVersion: string;
  dataVersion: string;
}

export const isOutside = (c: Comparison): boolean => Math.abs(c.simulated - c.expected) > c.tolerance;

/** A share is shown as a percentage; a count or a year as it is. */
const figure = (c: Comparison, value: number): string =>
  c.name.includes("age at first marriage") || c.name.includes("per woman") || c.name.includes("per person")
    ? value.toFixed(2)
    : c.name.includes("correlation") || c.name.includes("distance")
      ? value.toFixed(3)
      : `${(value * 100).toFixed(1)}%`;

const row = (cells: string[]) => `| ${cells.join(" | ")} |`;
const table = (head: string[], rows: string[][]) =>
  [row(head), row(head.map((_, i) => (i === 0 ? "---" : "---:"))), ...rows.map(row)].join("\n");

const lifeExpectancyOutside = (c: CountryBalance) => Math.abs(c.lifeExpectancy.difference) > LE_TOLERANCE_YEARS;

export function renderBalanceReport({ countries, lives, contentVersion, dataVersion }: BalanceReportInput): string {
  const lines = [
    "# Balance report",
    "",
    `Generated by \`npm run balance-report\` (ADMIN-003). Do not edit by hand. Content version ${contentVersion}, data version ${dataVersion}.`,
    "",
    `For each country, ${lives} default-course lives were simulated and compared with the source data (UN, World Bank, WHO, UNESCO and others; see the sources screen). A figure is **outside** when it is further from the source than its tolerance. The tolerances are the ones the calibration tests use, and the cause-of-death tolerance is 5 points of share. A figure outside tolerance is a finding to look at, not always a fault: some countries publish figures that no single model can hold together (see \`docs/design.md\` section 7).`,
    "",
    "## Summary",
    "",
    table(
      ["Country", "Income group", "Life expectancy, source", "Life expectancy, simulated", "Figures outside tolerance"],
      countries.map((c) => {
        const outside = c.comparisons.filter(isOutside).length + Number(lifeExpectancyOutside(c));
        return [
          `${c.country.name} (${c.country.iso3})`,
          c.country.incomeGroup,
          c.lifeExpectancy.expected.toFixed(1),
          c.lifeExpectancy.simulated.toFixed(1),
          `${outside} of ${c.comparisons.length + 1}`,
        ];
      }),
    ),
    "",
  ];
  for (const c of countries) {
    lines.push(
      `## ${c.country.name} (${c.country.iso3})`,
      "",
      `${c.country.region}, ${c.country.incomeGroup} income.`,
      "",
      table(
        ["Figure", "Source", "Simulated", "Tolerance", ""],
        [
          [
            "life expectancy at birth (years)",
            c.lifeExpectancy.expected.toFixed(1),
            c.lifeExpectancy.simulated.toFixed(1),
            `${LE_TOLERANCE_YEARS}`,
            lifeExpectancyOutside(c) ? "**outside**" : "ok",
          ],
          ...c.comparisons.map((m) => [
            m.name,
            figure(m, m.expected),
            figure(m, m.simulated),
            figure(m, m.tolerance),
            isOutside(m) ? "**outside**" : "ok",
          ]),
        ],
      ),
      "",
    );
  }
  return lines.join("\n");
}
