// The agency probe's report as Markdown (ADMIN-005): written to docs/agency-probe.md by `npm run probe`
// and published by CI. A pure function of the probe's numbers, so a test can check it.
import {
  METRICS,
  balanceChecks,
  isClear,
  type AreaReport,
  type DecisionReportRow,
  type Estimate,
  type Metric,
  type StrategyReport,
} from "./probe";

export interface ProbeReportInput {
  strategies: AreaReport;
  decisions: DecisionReportRow[];
  seed: string;
  decisionLives: number;
  contentVersion: string;
  dataVersion: string;
}

/** Shares and rates are shown as percentage points, years and points as they are. */
const SHARE_METRICS: readonly Metric[] = ["outOfWork", "choiceShare", "circumstanceShare", "chanceShare"];

/** The measures whose columns the tables show: the shares have their own table. */
const SHOWN = METRICS.filter((m) => m.id !== "choiceShare" && m.id !== "choiceNamed");

const sign = (x: number) => (x > 0 ? "+" : x < 0 ? "−" : "");

function formatDelta(metric: Metric, e: Estimate): string {
  if (e.n === 0) return "n/a";
  const share = SHARE_METRICS.includes(metric);
  const value = share ? e.mean * 100 : e.mean;
  const digits = metric === "wealth45" ? 2 : share ? 1 : 1;
  const text = `${sign(Math.abs(value) < 0.05 ? 0 : value)}${Math.abs(value).toFixed(digits)}${share ? " pp" : ""}`;
  // A difference that shows as zero is never bold, whatever its standard error.
  return isClear(e) && /[1-9]/.test(text) ? `**${text}**` : text;
}

function formatMean(metric: Metric, mean: number): string {
  if (SHARE_METRICS.includes(metric)) return `${(mean * 100).toFixed(1)}%`;
  return metric === "wealth45" ? mean.toFixed(2) : mean.toFixed(1);
}

const row = (cells: string[]) => `| ${cells.join(" | ")} |`;
const table = (head: string[], rows: string[][]) =>
  [row(head), row(head.map((_, i) => (i === 0 ? "---" : "---:"))), ...rows.map(row)].join("\n");

const DELTA_COLUMNS = SHOWN;

function strategyTable(strategies: StrategyReport[]): string {
  return table(
    ["Plan", ...DELTA_COLUMNS.map((m) => m.label), "Choice share", "Stats naming choice"],
    strategies
      .filter((s) => s.strategy.plan.kind !== "default")
      .map((s) => [
        s.strategy.label,
        ...DELTA_COLUMNS.map((m) => formatDelta(m.id, s.versusDefault[m.id])),
        formatDelta("choiceShare", s.versusDefault.choiceShare),
        formatDelta("choiceNamed", s.versusDefault.choiceNamed),
      ]),
  );
}

function sharesTable(strategies: StrategyReport[]): string {
  return table(
    ["Plan", "Circumstance", "Choice", "Chance", "Stats where the summary names choice (of 4)"],
    strategies.map((s) => [
      s.strategy.label,
      formatMean("circumstanceShare", s.means.circumstanceShare),
      formatMean("choiceShare", s.means.choiceShare),
      formatMean("chanceShare", s.means.chanceShare),
      s.means.choiceNamed.toFixed(2),
    ]),
  );
}

function meansTable(strategies: StrategyReport[]): string {
  return table(
    ["Plan", ...DELTA_COLUMNS.map((m) => m.label)],
    strategies.map((s) => [s.strategy.label, ...DELTA_COLUMNS.map((m) => formatMean(m.id, s.means[m.id]))]),
  );
}

function decisionsTable(rows: DecisionReportRow[]): string {
  const columns = ["lifespan", "rank35", "happiness", "belonging", "wealth45", "choiceShare"] as const;
  const label = (id: (typeof columns)[number]) => METRICS.find((m) => m.id === id)!.label;
  return table(
    ["Decision", "Choice", "Lives", ...columns.map(label)],
    rows.map((r) => [
      r.eventId,
      r.isDefault ? `${r.choiceId} (default)` : r.choiceId,
      String(r.lives),
      ...columns.map((id) => (r.isDefault ? "—" : formatDelta(id, r.versusDefault[id]))),
    ]),
  );
}

export function renderProbeReport(input: ProbeReportInput): string {
  const { strategies, decisions, seed, decisionLives, contentVersion, dataVersion } = input;
  const lines = [
    "# Agency probe",
    "",
    `Generated by \`npm run probe\` (ADMIN-005). Do not edit by hand. Seed \`${seed}\`, content version ${contentVersion}, data version ${dataVersion}.`,
    "",
    `${strategies.lives} lives, born where the odds of birth put them, were played once under each plan. Every plan is compared with the default course on the same lives (same seed, so the same birth and the same luck until the plan makes a difference). A **bold** difference is more than two standard errors from zero; the rest is not distinguishable from noise at this sample size.`,
    "",
    "## Balance targets",
    "",
    "The first balance pass's targets (`balanceChecks` in `src/engine/probe.ts`), read off the numbers below.",
    "",
    table(
      ["Target", "Result", "Measured"],
      balanceChecks(strategies).map((c) => [c.target, c.pass ? "met" : "**not met**", c.detail]),
    ),
    "",
    "## What each plan changes",
    "",
    "Differences from the default course. Points of the stat, years, or percentage points (pp) of a share.",
    "",
    strategyTable(strategies.strategies),
    "",
    "## What shaped the life (summary shares)",
    "",
    "The shares the summary screen reports (SUM-004), averaged over the lives of each plan. Accepting the default plan counts part as choice, and the more points a player moves away from it the more of it is theirs; a plan with all its points in one area is worth little more than the default in the stat it neglects, so it can show less choice than a plan with one point moved.",
    "",
    sharesTable(strategies.strategies),
    "",
    "## Mean outcomes",
    "",
    meansTable(strategies.strategies),
    "",
    "## What each decision's choices change",
    "",
    `The first time each decision came up in ${decisionLives} default-course lives, the life was forked: each open choice was taken in turn and the rest of the life played by the default course. Differences are from the default choice of the same decision; the first choice listed is that default. Decisions that came up in fewer than 10 lives are left out.`,
    "",
    decisionsTable(
      decisions.filter((r) => decisions.some((d) => d.eventId === r.eventId && d.isDefault && d.lives >= 10)),
    ),
    "",
  ];
  return lines.join("\n");
}
